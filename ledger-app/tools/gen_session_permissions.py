#!/usr/bin/env python3
"""Generate src/xrp/session_permissions.c from the rippled protocol macros.

A session in mode P carries XLS-75 permission values (FIANSO-SPEC 6.3, 7.3 f):
  - a delegable transaction type T is permission value T + 1;
  - a granular permission has its own value (>= 65537).
The device must name every value it shows; any other value forces blind
signing. The names are the rippled names, so the screen reads like the JSON.

Usage (from ledger-app/): python3 tools/gen_session_permissions.py
"""

import re
from pathlib import Path

APP_DIR = Path(__file__).resolve().parent.parent
MACRO_DIR = APP_DIR.parent / "rippled" / "include" / "xrpl" / "protocol" / "detail"
TRANSACTIONS_MACRO = MACRO_DIR / "transactions.macro"
PERMISSIONS_MACRO = MACRO_DIR / "permissions.macro"
OUTPUT = APP_DIR / "src" / "xrp" / "session_permissions.c"

TRANSACTION_RE = re.compile(r"^TRANSACTION\((tt\w+),\s*(\d+),\s*(\w+),\s*\(\{(.*?)\}\)", re.S | re.M)
GRANULAR_RE = re.compile(r"^GRANULAR_PERMISSION\((\w+),\s*\w+,\s*(\d+)", re.M)
DELEGABLE = "Delegation::Delegable"
TRANSACTION_PERMISSION_OFFSET = 1

HEADER = """\
/*******************************************************************************
 *   carbs: XLS-75 permission names shown in a signing session review.
 *
 *   GENERATED by tools/gen_session_permissions.py from
 *   rippled/include/xrpl/protocol/detail/{transactions,permissions}.macro.
 *   Do not edit by hand: run the script again.
 ********************************************************************************/

#include "session_permissions.h"

#include <stddef.h>

const char *resolve_permission_name(uint32_t value) {
    switch (value) {
"""

FOOTER = """\
        default:
            return NULL;
    }
}
"""


def delegable_transactions(text: str) -> list[tuple[int, str]]:
    found = [(int(value), name) for _, value, name, settings in TRANSACTION_RE.findall(text) if DELEGABLE in settings]
    if not found:
        raise SystemExit(f"no delegable transaction found in {TRANSACTIONS_MACRO}")
    return found


def granular_permissions(text: str) -> list[tuple[int, str]]:
    found = [(int(value), name) for name, value in GRANULAR_RE.findall(text)]
    if not found:
        raise SystemExit(f"no granular permission found in {PERMISSIONS_MACRO}")
    return found


def main() -> None:
    entries = [
        (tx_type + TRANSACTION_PERMISSION_OFFSET, name)
        for tx_type, name in delegable_transactions(TRANSACTIONS_MACRO.read_text())
    ]
    entries += granular_permissions(PERMISSIONS_MACRO.read_text())
    values = [value for value, _ in entries]
    if len(values) != len(set(values)):
        raise SystemExit("duplicate permission value in the rippled macros")

    cases = "".join(f'        case {value}:\n            return "{name}";\n' for value, name in sorted(entries))
    OUTPUT.write_text(HEADER + cases + FOOTER)
    print(f"{OUTPUT.relative_to(APP_DIR)}: {len(entries)} permissions")


if __name__ == "__main__":
    main()
